"""RAG pipeline behind the explorer: load -> chunk -> embed -> retrieve -> generate.

Embeddings are computed locally (Chroma's bundled all-MiniLM-L6-v2 ONNX model, since Groq has
no embeddings API). The answer is generated by Groq through its OpenAI-compatible API.
Every step is plain numpy on purpose, so the explorer can show exactly what is happening.
"""
import math
import os
import re
import threading
import time
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from dotenv import load_dotenv
from openai import OpenAI, OpenAIError

HERE = Path(__file__).parent
load_dotenv(HERE / ".env")  # reads ragExplorer/.env

DATA_DIR = Path(os.getenv("DATA_DIR", HERE / "data"))
DOC_SUFFIXES = {".md", ".txt"}
DEFAULT_MODEL = "openai/gpt-oss-120b"
DEFAULT_BASE_URL = "https://api.groq.com/openai/v1"
EMBEDDING_MODEL = "all-MiniLM-L6-v2"
MAX_INDEXES = 8  # cached indexes (one per chunking setting); oldest is dropped beyond this
RRF_K = 60  # reciprocal-rank-fusion constant used by hybrid retrieval

STRATEGIES = ("section", "fixed")
MODES = ("semantic", "keyword", "hybrid")

SYSTEM_PROMPT = """You are a question-answering assistant. Answer using ONLY the numbered context passages below.

Rules:
1. Base every statement on the passages. Never use outside knowledge, even if you know the answer.
2. Cite the passages you used inline, like [1] or [2][3].
3. If the passages do not contain the answer, say you can't answer that from the provided documents.
4. Be concise.

<context>
__CONTEXT__
</context>"""

STOPWORDS = frozenset(
    "a an and are as at be by can do does for from how i if in is it my of on or that the "
    "this to was what when where which who why will with you your".split()
)


@dataclass
class Chunk:
    id: int
    doc: str  # path relative to DATA_DIR
    heading: str  # "Title > Section" the chunk sits under ("" if none)
    text: str  # exactly what gets embedded and sent to the LLM


# ---- loading + chunking ---------------------------------------------------------------
def corpus_signature():
    """Cheap fingerprint of the data folder, so edits to the files invalidate cached indexes."""
    return tuple(
        (p.relative_to(DATA_DIR).as_posix(), p.stat().st_mtime_ns, p.stat().st_size)
        for p in sorted(DATA_DIR.rglob("*"))
        if p.is_file() and p.suffix in DOC_SUFFIXES
    )


def load_documents():
    docs = {
        p.relative_to(DATA_DIR).as_posix(): p.read_text(encoding="utf-8")
        for p in sorted(DATA_DIR.rglob("*"))
        if p.is_file() and p.suffix in DOC_SUFFIXES
    }
    if not docs:
        raise FileNotFoundError(f"No .md or .txt files found in {DATA_DIR}")
    return docs


def window(text, size, overlap):
    """Split text into pieces of about `size` chars; each shares ~`overlap` chars with the last.

    Cuts snap back to a paragraph break, else a line break, else a space (never mid-word).
    """
    text = text.strip()
    if len(text) <= size:
        return [text] if text else []

    pieces, start = [], 0
    while start < len(text):
        end = min(start + size, len(text))
        if end < len(text):
            for sep in ("\n\n", "\n", " "):
                cut = text.rfind(sep, start + size // 2, end)
                if cut != -1:
                    end = cut
                    break
        piece = text[start:end].strip()
        if piece:
            pieces.append(piece)
        if end >= len(text):
            break
        nxt = end - overlap
        if nxt <= start:  # overlap >= piece length would loop forever
            nxt = end
        while 0 < nxt < len(text) and not text[nxt - 1].isspace():
            nxt += 1  # start the next piece on a word boundary
        start = nxt
    return pieces


def split_sections(text):
    """Yield (heading_path, body) for each markdown heading section, in file order."""
    stack = []  # [(level, title)]
    body = []
    sections = []

    def flush():
        joined = "\n".join(body).strip()
        if joined:
            sections.append((" > ".join(t for _, t in stack), joined))
        body.clear()

    for line in text.splitlines():
        m = re.match(r"^(#{1,6})\s+(.*\S)\s*$", line)
        if m:
            flush()
            level = len(m.group(1))
            while stack and stack[-1][0] >= level:
                stack.pop()
            stack.append((level, m.group(2)))
        else:
            body.append(line)
    flush()
    return sections


def build_chunks(docs, strategy, size, overlap):
    """Chunk every document.

    section: one chunk per markdown section, prefixed with its heading path (so "30 days"
             still says it belongs to the Return Policy); oversized sections are windowed.
    fixed:   sliding window over the raw file, ignoring structure.
    """
    chunks = []

    def add(doc, heading, text):
        chunks.append(Chunk(len(chunks), doc, heading, text))

    for doc, text in docs.items():
        if strategy == "fixed":
            for piece in window(text, size, overlap):
                add(doc, "", piece)
        else:
            for heading, body in split_sections(text):
                prefix = f"{heading}\n" if heading else ""
                # leave room for the heading prefix so the whole chunk stays within `size`
                room = max(size - len(prefix), size // 2)
                for piece in window(body, room, min(overlap, room - 1)):
                    add(doc, heading, prefix + piece)
    return chunks


# ---- embeddings -----------------------------------------------------------------------
class Embedder:
    """Local sentence embeddings, L2-normalised so a dot product is cosine similarity."""

    def __init__(self):
        from chromadb.utils.embedding_functions import DefaultEmbeddingFunction

        self._fn = DefaultEmbeddingFunction()  # downloads ~80 MB on first run, then cached
        self._cache = {}  # text -> unit vector, so re-chunking only embeds new text
        self._lock = threading.Lock()

    def embed(self, texts):
        with self._lock:
            missing = [t for t in dict.fromkeys(texts) if t not in self._cache]
            if missing:
                vecs = np.asarray(self._fn(missing), dtype=np.float32)
                vecs /= np.linalg.norm(vecs, axis=1, keepdims=True)
                self._cache.update(zip(missing, vecs))
            return np.stack([self._cache[t] for t in texts])


# ---- keyword scoring ------------------------------------------------------------------
def tokenize(text):
    words = re.findall(r"[a-z0-9]+", text.lower())
    # crude plural stripping so "refunds" matches "refund"; real stemmers do much more
    return [w[:-1] if len(w) > 3 and w.endswith("s") and not w.endswith("ss") else w
            for w in words if w not in STOPWORDS]


class BM25:
    def __init__(self, texts, k1=1.5, b=0.75):
        self.k1, self.b = k1, b
        self.tf = [Counter(tokenize(t)) for t in texts]
        self.len = np.array([sum(c.values()) for c in self.tf], dtype=np.float32)
        self.avg_len = float(self.len.mean()) or 1.0
        df = Counter(term for c in self.tf for term in c)
        n = len(texts)
        self.idf = {t: math.log(1 + (n - d + 0.5) / (d + 0.5)) for t, d in df.items()}

    def scores(self, query):
        out = np.zeros(len(self.tf), dtype=np.float32)
        for term in set(tokenize(query)):
            idf = self.idf.get(term)
            if idf is None:
                continue
            for i, tf in enumerate(self.tf):
                f = tf.get(term, 0)
                if f:
                    norm = self.k1 * (1 - self.b + self.b * self.len[i] / self.avg_len)
                    out[i] += idf * f * (self.k1 + 1) / (f + norm)
        return out


# ---- index + retrieval ----------------------------------------------------------------
class Index:
    def __init__(self, chunks, embedder):
        self.chunks = chunks
        self.embedder = embedder
        self.vectors = embedder.embed([c.text for c in chunks])
        self.bm25 = BM25([c.text for c in chunks])

        # 2-D PCA of the embeddings, purely for the explorer's chunk map
        self.mean = self.vectors.mean(axis=0)
        _, _, vt = np.linalg.svd(self.vectors - self.mean, full_matrices=False)
        self.components = np.zeros((2, self.vectors.shape[1]), dtype=np.float32)
        self.components[: min(2, len(vt))] = vt[:2]
        self.coords = self._project(self.vectors)

    def _project(self, vecs):
        return (vecs - self.mean) @ self.components.T

    def search(self, query, mode, top_k):
        """Return (hits, query_xy). Each hit: dict(chunk, score, semantic, keyword)."""
        q = self.embedder.embed([query])[0]
        semantic = self.vectors @ q
        keyword = self.bm25.scores(query)

        sem_rank = {int(i): r for r, i in enumerate(np.argsort(-semantic), start=1)}
        kw_rank = {
            int(i): r
            for r, i in enumerate((i for i in np.argsort(-keyword) if keyword[i] > 0), start=1)
        }

        if mode == "semantic":
            score, order = semantic, np.argsort(-semantic)
        elif mode == "keyword":
            # chunks sharing no term with the query are not retrieved at all
            score, order = keyword, [i for i in np.argsort(-keyword) if keyword[i] > 0]
        else:  # hybrid: reciprocal rank fusion of the two rankings
            score = np.array(
                [
                    1 / (RRF_K + sem_rank[i]) + (1 / (RRF_K + kw_rank[i]) if i in kw_rank else 0)
                    for i in range(len(self.chunks))
                ],
                dtype=np.float32,
            )
            order = np.argsort(-score)

        hits = [
            {
                "chunk": self.chunks[int(i)],
                "score": float(score[i]),
                "semantic": float(semantic[i]),
                "keyword": float(keyword[i]),
            }
            for i in list(order)[:top_k]
        ]
        return hits, self._project(q[None, :])[0]


class Explorer:
    """Holds the embedder, a small cache of indexes, and the Groq client."""

    def __init__(self):
        self.embedder = Embedder()
        self._indexes = {}
        self._lock = threading.Lock()

        self.model = os.getenv("GROQ_MODEL", DEFAULT_MODEL)
        api_key = os.getenv("GROQ_API_KEY")
        self.client = (
            OpenAI(
                api_key=api_key,
                base_url=os.getenv("GROQ_BASE_URL", DEFAULT_BASE_URL),
                timeout=60,
            )
            if api_key
            else None
        )

    def index_for(self, strategy, size, overlap):
        key = (strategy, size, overlap, corpus_signature())
        with self._lock:
            if key not in self._indexes:
                chunks = build_chunks(load_documents(), strategy, size, overlap)
                self._indexes[key] = Index(chunks, self.embedder)
                while len(self._indexes) > MAX_INDEXES:
                    self._indexes.pop(next(iter(self._indexes)))
            return self._indexes[key]

    def generate(self, query, hits):
        """Ask Groq to answer from the retrieved chunks. Returns (answer, messages, usage)."""
        context = "\n\n".join(
            f"[{n}] (source: {h['chunk'].doc}"
            + (f" > {h['chunk'].heading}" if h["chunk"].heading else "")
            + f")\n{h['chunk'].text}"
            for n, h in enumerate(hits, start=1)
        ) or "(no passages were retrieved)"
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT.replace("__CONTEXT__", context)},
            {"role": "user", "content": query},
        ]
        response = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            temperature=0.2,  # low: we want answers faithful to the passages
        )
        answer = (response.choices[0].message.content or "").strip()
        usage = response.usage.model_dump() if response.usage else None
        return answer, messages, usage

    def query(self, query, settings, generate):
        """Run retrieval (and optionally generation). Returns a JSON-ready dict."""
        index = self.index_for(settings["strategy"], settings["chunk_size"], settings["overlap"])
        t0 = time.perf_counter()
        hits, query_xy = index.search(query, settings["mode"], settings["top_k"])
        result = {
            "hits": [
                {
                    "rank": r,
                    "id": h["chunk"].id,
                    "score": h["score"],
                    "semantic": h["semantic"],
                    "keyword": h["keyword"],
                }
                for r, h in enumerate(hits, start=1)
            ],
            "query_xy": query_xy.tolist(),
            "retrieval_ms": round((time.perf_counter() - t0) * 1000),
        }

        if generate:
            result.update(answer=None, answer_error=None, prompt=None, usage=None)
            if self.client is None:
                result["answer_error"] = "GROQ_API_KEY is not set. Copy .env.example to .env and add your key."
            else:
                t1 = time.perf_counter()
                try:
                    answer, messages, usage = self.generate(query, hits)
                except OpenAIError as e:  # keep the retrieval results even if the LLM call fails
                    result["answer_error"] = f"Could not reach the LLM: {e}"
                else:
                    result.update(
                        answer=answer or "(the model returned an empty answer)",
                        prompt=messages,
                        usage=usage,
                        generation_ms=round((time.perf_counter() - t1) * 1000),
                    )
        return result
